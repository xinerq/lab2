def area(a, h):
    """
    Returns area of triangle
    
        Input: 
            a(int/float) : side
            h(int/float) : height
        Output:
            triangle_area(float/int)
    """
    return a * h / 2

def perimeter(a, b, c):
    """
    Returns perimeter of triangle

        Input:
            a(int/float) : first side
            b(int/float) : second side
            c(int/float) : third side
        Output:
            triangle_perimeter(int/float)
    """
    return a + b + c