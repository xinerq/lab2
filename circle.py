import math


def area(r):
    """
    Returns area of circle

        Input:
            r(int/float) : radius
        Output:
            area_of_circle(float)
    """
    return math.pi * r * r


def perimeter(r):
    """
    Returns perimeter of circle

        Input:
            r(int/float) : radius
        Output:
            perimeter_of_circle(float)
    """
    return 2 * math.pi * r

