def area(a, b):
    """
    Returns area of rectangle

        Input:
            a(int/float) : first side
            b(int/float) : second side
        Output:
            area_of_rectangle(int/float)
    """
    return a * b
 
def perimeter(a, b):
    """
    Returns perimeter of rectangle
    
        Input:
            a(int/float) : first side
            b(int/float) : second side
        Output:
            perimeter_of_rectangle(int/float)
    """
    return 2*(a + b)