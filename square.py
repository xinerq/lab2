
def area(a):
    """
    Returns area of square
    
        Input:
            a(int/float) : square side
        Output:
            area_of_square(int/float)
    """
    return a * a


def perimeter(a):
    """
    Returns perimeter of sqare
        
        Input:
            a(int/float) : square side
        Output:
            perimeter_of_square(int/float)
    """
    return 4 * a
